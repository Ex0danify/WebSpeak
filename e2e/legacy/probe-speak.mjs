import { launch, writeTone, openSession } from "./lib.mjs";
const SP = new URL(".", import.meta.url).pathname;
writeTone(SP + "tone.wav", { amp: 0.6 });
const browser = await launch(SP + "tone.wav");
const A = await openSession(browser, "smoke-A"); const B = await openSession(browser, "smoke-B");
await B.page.waitForTimeout(3000);
const types = {}; for (const m of B.texts) types[m.type] = (types[m.type] || 0) + 1;
console.log("B msg types", JSON.stringify(types));
console.log("speaking-ish DOM at B:", await B.page.evaluate(() => [...document.querySelectorAll("[class*=speaking],[aria-label*=peaking]")].slice(0, 6).map((e) => e.tagName + "." + e.className.toString().slice(0, 50) + " | " + (e.getAttribute("aria-label") || e.textContent.trim().slice(0, 30)))));
console.log("current channel DOM at A:", await A.page.evaluate(() => [...document.querySelectorAll("[class*=current],[aria-current]")].slice(0, 4).map((e) => e.tagName + "." + e.className.toString().slice(0, 60) + " | " + e.textContent.trim().slice(0, 30))));
await browser.close();
