import { chromium, launch, writeTone, URL_BASE } from "./lib.mjs";
const SP = new URL(".", import.meta.url).pathname;
writeTone(SP + "silence-ish.wav", { amp: 0.0 });
const browser = await launch(SP + "silence-ish.wav");
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, permissions: ["microphone"], locale: "en" });
const page = await ctx.newPage();
const wsLog = [];
page.on("websocket", (ws) => { ws.on("framereceived", (f) => { if (typeof f.payload === "string") wsLog.push(f.payload.slice(0, 300)); }); });
page.on("console", (m) => { if (m.type() === "error") console.log("[console.error]", m.text().slice(0, 200)); });
await page.goto(URL_BASE + "/", { waitUntil: "networkidle" });
await page.screenshot({ path: SP + "shots/00-join.png" });
console.log("form fields:", await page.$$eval(".join-form input, .join-form select, .join-form button", (els) => els.map((e) => `${e.tagName.toLowerCase()}#${e.id}[${e.type ?? ""}] ${(e.getAttribute("aria-label") || e.textContent || "").trim().slice(0, 40)}`)));
await page.fill("#nickname", "smoke-probe");
await page.click(".join-form button[type=submit]");
await page.waitForSelector(".join-page", { state: "detached", timeout: 20000 }).catch((e) => console.log("join did not leave join page:", e.message.split("\n")[0]));
await page.waitForTimeout(3000);
await page.screenshot({ path: SP + "shots/01-connected.png" });
console.log("ws text frames:", wsLog.map((s) => s.slice(0, 160)));
console.log("buttons:", await page.$$eval("button", (els) => els.filter((e) => e.offsetParent).map((e) => (e.getAttribute("aria-label") || e.getAttribute("title") || e.textContent || "").trim().replace(/\s+/g, " ").slice(0, 40))));
await browser.close();
