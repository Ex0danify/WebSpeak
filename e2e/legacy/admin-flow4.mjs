import { launch, rec, URL_BASE } from "./lib.mjs";
const SP = new URL(".", import.meta.url).pathname;
const browser = await launch(SP + "quiet.wav");
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "en" });
await ctx.addInitScript(() => { try { localStorage.setItem("webspeak:language", "en"); } catch {} });
const p = await ctx.newPage();
await p.goto(URL_BASE + "/admin/login", { waitUntil: "networkidle" });
await p.locator("input[type=text]").first().fill("admin"); await p.locator("input[type=password]").first().fill("Smoke-Test-Pass-2026!"); await p.locator("button[type=submit]").click();
await p.waitForURL(/\/admin$/); await p.getByRole("link", { name: "Server" }).first().click(); await p.waitForTimeout(1200);
await p.getByRole("button", { name: "Test connection" }).click(); await p.waitForTimeout(4000);
await p.screenshot({ path: SP + "shots/79-admin-test-conn.png" });
const txt = await p.locator("main, body").first().innerText();
const m = txt.match(/(reachable|success|connected|available|failed|timeout|unreachable|version|latency|ms)[^\n]{0,80}/i);
rec("12", "'Test connection' probes the real TeamSpeak server", /success|reachable|connected|ok|available|version|ms/i.test(txt) && !/failed|unreachable|timed out/i.test(txt.split("Test connection").pop().slice(0, 300)), (m?.[0] || txt.split("Test connection").pop().replace(/\s+/g, " ").slice(0, 160)));
await browser.close();
